"""Markdown export of a workspace: every host and everything the phases collected.

A pure function over a DB session (no console, no files), so it's testable with
an in-memory database. The text it embeds comes from the scanned targets
(banners, page URLs, emails), so it is untrusted: table cells have `|` and
newlines neutralised and `<`/`>` escaped, so a hostile banner can neither break
a table nor inject HTML into a Markdown renderer.
"""
from datetime import datetime, timezone

from model.host import Host
from model.scope_model import ScopeRule
from model.service_model import Service, current_services_filter


def _cell(value) -> str:
    text = '-' if value is None or value == '' else str(value)
    text = ' '.join(text.splitlines())
    return text.replace('<', '&lt;').replace('>', '&gt;').replace('|', '\\|')


def _when(value) -> str:
    return value.strftime('%Y-%m-%d %H:%M') if value else '-'


def _table(headers, rows) -> list[str]:
    lines = ['| ' + ' | '.join(headers) + ' |', '|' + '|'.join(['---'] * len(headers)) + '|']
    lines += ['| ' + ' | '.join(_cell(c) for c in row) + ' |' for row in rows]
    return lines + ['']


def _service_label(service: Service) -> str:
    return f"{service.product or service.name or '?'} {service.version or ''}".strip()


def build_workspace_report(session, workspace_id: int, workspace_name: str, now: datetime | None = None) -> str:
    now = now or datetime.now(timezone.utc)
    hosts = session.query(Host).filter_by(workspace_id=workspace_id).order_by(Host.addr).all()
    rules = (
        session.query(ScopeRule).filter_by(workspace_id=workspace_id)
        .order_by(ScopeRule.allow.desc(), ScopeRule.value).all()
    )
    current = {
        host.id: session.query(Service)
        .filter(Service.host_id == host.id, current_services_filter())
        .order_by(Service.port).all()
        for host in hosts
    }

    out = [
        f'# Sharingan report: {_cell(workspace_name)}', '',
        f'- Generated: {now.strftime("%Y-%m-%d %H:%M")} UTC',
        f'- Hosts: {len(hosts)}', '',
        '## Scope', '',
    ]
    if rules:
        out += _table(['Rule', 'Type', 'Value'],
                      [('include' if r.allow else 'exclude', r.kind, r.value) for r in rules])
    else:
        out += ['No scope defined: any target could be scanned.', '']

    out += ['## Summary', '']
    if not hosts:
        out += ['No hosts in this workspace yet.', '']
    else:
        rows = []
        for host in hosts:
            services = current[host.id]
            rows.append((
                host.addr, host.nome, len(services),
                sum(len(s.vulnerabilities) for s in services),
                sum(len(s.exploit_matches) for s in services),
                len(host.subdomain_records), len(host.crawled_pages),
                len(host.harvested_emails), len(host.findings),
            ))
        out += _table(['Host', 'Name', 'Services', 'Vulnerabilities', 'Exploits',
                       'Subdomains', 'Pages', 'Emails', 'Findings'], rows)

    for host in hosts:
        out += _host_section(host, current[host.id])

    out += ['---', '',
            '_Generated by Sharingan. Use it only against targets you are authorized to test._', '']
    return '\n'.join(out)


def _host_section(host: Host, services: list[Service]) -> list[str]:
    out = [f'## {_cell(host.addr)} ({_cell(host.nome)})', '']
    sections = []

    whois = max(host.whois_records, key=lambda r: r.id, default=None)
    if whois:
        sections += ['### WHOIS', ''] + _table(['Property', 'Value'], [
            ('Registrar', whois.registrar), ('Created', _when(whois.creation_date)),
            ('Expires', _when(whois.expiration_date)), ('Looked up', _when(whois.created_at)),
        ])
    if host.subdomain_records:
        sections += ['### Subdomains', ''] + [
            f'- {_cell(s.name)}' for s in sorted(host.subdomain_records, key=lambda s: s.name)
        ] + ['']

    if services:
        sections += ['### Services', ''] + _table(
            ['Port', 'State', 'Service', 'CVEs', 'Exploits'],
            [(s.port, s.state, _service_label(s), len(s.vulnerabilities), len(s.exploit_matches))
             for s in services])
        vulns = sorted(
            ((s, v) for s in services for v in s.vulnerabilities),
            key=lambda pair: pair[1].cvss or 0, reverse=True,
        )
        if vulns:
            sections += ['### Vulnerabilities', ''] + _table(
                ['CVE', 'CVSS', 'Port', 'Service', 'Reference'],
                [(v.cve, v.cvss, s.port, _service_label(s), v.reference) for s, v in vulns])
        exploits = [(s, e) for s in services for e in sorted(s.exploit_matches, key=lambda e: e.title)]
        if exploits:
            sections += ['### Exploits', ''] + _table(
                ['Port', 'Service', 'Title', 'EDB-ID', 'Verified', 'CVEs'],
                [(s.port, _service_label(s), e.title, e.edb_id,
                  'yes' if e.verified else 'no', (e.cve_codes or '').replace(';', ', ')) for s, e in exploits])

    if host.scan_runs:
        sections += ['### Scan history', ''] + _table(
            ['Run', 'Status', 'Started', 'Finished'],
            [(r.id, r.status, _when(r.started_at), _when(r.finished_at))
             for r in sorted(host.scan_runs, key=lambda r: r.id, reverse=True)])
    if host.crawled_pages:
        sections += ['### Crawled pages', ''] + _table(
            ['URL', 'Code', 'Depth'],
            [(p.url, p.status_code, p.depth) for p in sorted(host.crawled_pages, key=lambda p: p.url)])
    if host.harvested_emails:
        sections += ['### Emails', ''] + _table(
            ['Email', 'Found on'],
            [(e.email, e.source_url) for e in sorted(host.harvested_emails, key=lambda e: e.email)])
    if host.findings:
        sections += ['### Directory findings', ''] + _table(
            ['URL', 'Path', 'Code', 'Size', 'Redirect'],
            [(f.url, f.path, f.status_code, f.size, f.redirect)
             for f in sorted(host.findings, key=lambda f: (f.url, f.path))])

    if not sections:
        return out + ['_No results have been collected for this host yet._', '']
    return out + sections
