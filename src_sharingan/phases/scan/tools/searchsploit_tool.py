import json
import shutil
import subprocess


class SearchsploitTool:
    """Thin wrapper around `searchsploit --nmap <xml>` (exploitdb package).

    Consumes the XML already generated by NmapTool and returns the exploit-db
    entries that match the identified products/versions.
    """

    binary = 'searchsploit'
    # `searchsploit --nmap` needs `xmllint` to parse the nmap XML —
    # without it the process exits with "[!] Please install xmllint" and status 1
    # (a known requirement, not a bug of ours: see Sn1per issue #72,
    # "kali needs xmllint for sniper's call to searchsploit"). Package:
    # `libxml2-utils` on Debian/Ubuntu, `libxml2` on Fedora/Arch/Homebrew.
    xmllint_binary = 'xmllint'

    @classmethod
    def is_available(cls) -> bool:
        return shutil.which(cls.binary) is not None and shutil.which(cls.xmllint_binary) is not None

    @classmethod
    def search_nmap_xml(cls, xml_path: str) -> list[dict]:
        if shutil.which(cls.binary) is None:
            raise RuntimeError(
                f"'{cls.binary}' not found in PATH. Install exploitdb "
                '(apt install exploitdb, or https://github.com/offensive-security/exploitdb) '
                'before using exploit correlation.'
            )
        if shutil.which(cls.xmllint_binary) is None:
            raise RuntimeError(
                f"'{cls.binary}' is in PATH but '{cls.xmllint_binary}' is not — "
                "--nmap mode depends on it to parse the XML. Install libxml2-utils "
                '(apt install libxml2-utils; on Fedora/Arch/macOS: libxml2 package).'
            )

        result = subprocess.run(
            [cls.binary, '--nmap', xml_path, '-j'],
            capture_output=True,
            text=True,
            check=True,
        )
        return cls._parse_json(result.stdout)

    @staticmethod
    def _parse_json(output: str) -> list[dict]:
        if not output.strip():
            return []
        try:
            data = json.loads(output)
        except json.JSONDecodeError:
            return []
        return data.get('RESULTS_EXPLOIT', [])
